import 'dart:convert';
import 'dart:io';

import 'package:cockpit/app/cockpit/data/hooks/hook_installer_base.dart';
import 'package:flutter/foundation.dart';

/// Instalador do status de turno no **Pi** (`pi`, `@earendil-works/pi-coding-agent`).
///
/// O Pi não tem hooks de shell como o Claude/Codex, mas carrega sozinho toda
/// extensão em `~/.pi/agent/extensions/` (arquivo `.js`/`.ts`, via jiti). Então
/// instalamos uma extensão mínima, [fileName], que traduz os eventos do Pi no
/// **mesmo envelope** do Claude e chama `<cli> hook --harness pi` pelo stdin —
/// o `cockpit hook` não sabe que é Pi além do `hn`:
///
/// | Evento do Pi | Envelope | Status |
/// |---|---|---|
/// | `session_start` | `SessionStart` (+ `session_id`, `transcript_path`) | idle |
/// | `agent_start` | `UserPromptSubmit` | working |
/// | `tool_result` de `edit`/`write` | `PostToolUse` `Edit`/`Write` + `file_path` | working + arquivos |
/// | `ui_prompt_start` / `_end` (só durante um run) | `PermissionRequest` / `PostToolUse` | waiting / working |
/// | `agent_end` | `Stop` | idle |
///
/// Só age dentro de uma aba do Cockpit (`COCKPIT_PANE_ID`) e no modo TUI. Fora
/// do TUI (`--mode rpc|json`, `-p`) troca o título do processo pra
/// `pi-<modo>`: o Pi grava `process.title = "pi"`, o que apaga o argv do
/// `/proc/<pid>/cmdline`/`ps`, e o classificador deixaria de ver o `--mode rpc`
/// (o `pi-rpc` é o mesmo nome que o próprio Pi usa no `rpc-entry`).
///
/// ponytail: fim de turno = `agent_end`, não `agent_settled` (Pi 1.3+; em
/// versão sem ele o spinner nunca apagaria). Retry automático do Pi vira um
/// idle curto entre dois runs. Pasta fixa `~/.pi/agent`: quem usa
/// `PI_CODING_AGENT_DIR` fica na heurística de saída.
///
/// Idempotente: grava só se o conteúdo mudou; arquivo com o mesmo nome sem o
/// [marker] (do usuário) não é tocado. Sem `~/.pi` o Pi nunca rodou: sai sem
/// criar nada.
class PiHookInstallerImpl extends HookInstallerBase {
  const PiHookInstallerImpl();

  @override
  String get harnessName => 'pi';

  static const String fileName = 'cockpit-hook.js';
  static const String marker = '// cockpit-hook (auto-generated by Cockpit';

  @override
  Future<void> writeConfig({
    required String home,
    required String command,
  }) async {
    if (!await Directory('$home/.pi').exists()) return;
    final file = File('$home/.pi/agent/extensions/$fileName');
    final content = extensionSource('$command --harness pi');
    if (await file.exists()) {
      final current = await file.readAsString();
      if (current == content || !current.startsWith(marker)) return;
    } else {
      await file.parent.create(recursive: true);
    }
    await file.writeAsString(content);
    if (kDebugMode) debugPrint('[pi-hook] extensão instalada em ${file.path}');
  }

  /// Fonte da extensão, com [command] embutido (string JSON: o caminho pode
  /// ter aspas/espaço). Inglês: é código, não texto de usuário.
  @visibleForTesting
  static String extensionSource(String command) =>
      '''
$marker; rewritten at every boot)
// Reports Pi's turn status and edited files to the Cockpit tab running it.
// To opt out, replace it with an empty file: Cockpit only writes files carrying
// this header (a deleted file comes back at the next boot).
import { spawn } from "node:child_process";

const COMMAND = ${jsonEncode(command)};
const TOOLS = { edit: "Edit", write: "Write" };

export default function (pi) {
  if (!process.env.COCKPIT_PANE_ID) return; // not a Cockpit tab
  let tui = false;
  let running = false;

  const send = (envelope) => {
    if (!tui) return;
    try {
      const child = spawn(COMMAND, { shell: true, stdio: ["pipe", "ignore", "ignore"] });
      child.on("error", () => {});
      child.stdin.on("error", () => {});
      child.stdin.end(JSON.stringify(envelope));
      child.unref();
    } catch {}
  };

  pi.on("session_start", (_event, ctx) => {
    tui = ctx?.mode === "tui";
    if (!tui) {
      process.title = "pi-" + (ctx?.mode ?? "headless"); // keeps `pi --mode rpc` out of tab detection
      return;
    }
    const sm = ctx?.sessionManager;
    send({
      hook_event_name: "SessionStart",
      session_id: sm?.getSessionId?.() ?? "",
      transcript_path: sm?.getSessionFile?.() ?? "",
      cwd: ctx?.cwd,
    });
  });
  pi.on("agent_start", (_event, ctx) => {
    running = true;
    send({ hook_event_name: "UserPromptSubmit", cwd: ctx?.cwd });
  });
  pi.on("agent_end", (_event, ctx) => {
    running = false;
    send({ hook_event_name: "Stop", cwd: ctx?.cwd });
  });
  pi.on("tool_result", (event, ctx) => {
    const tool = TOOLS[event.toolName];
    const path = event.input?.path;
    if (!tool || event.isError || typeof path !== "string") return;
    send({ hook_event_name: "PostToolUse", tool_name: tool, tool_input: { file_path: path }, cwd: ctx?.cwd });
  });
  pi.on("ui_prompt_start", (_event, ctx) => {
    if (running) send({ hook_event_name: "PermissionRequest", cwd: ctx?.cwd });
  });
  pi.on("ui_prompt_end", (_event, ctx) => {
    if (running) send({ hook_event_name: "PostToolUse", cwd: ctx?.cwd });
  });
}
''';
}
